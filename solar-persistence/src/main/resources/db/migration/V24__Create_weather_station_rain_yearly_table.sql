CREATE SEQUENCE IF NOT EXISTS WEATHER_STATION_RAIN_YEARLY_SEQ;

CREATE TABLE IF NOT EXISTS WEATHER_STATION_RAIN_YEARLY (
    ID INTEGER PRIMARY KEY NOT NULL DEFAULT nextval('WEATHER_STATION_RAIN_YEARLY_SEQ'),
    DATEUTC TIMESTAMPTZ NOT NULL,
    YEARLYRAININ NUMERIC(6, 3) NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_DATEUTC_WEATHER_STATION_RAIN_YEARLY ON WEATHER_STATION_RAIN_YEARLY(DATEUTC);