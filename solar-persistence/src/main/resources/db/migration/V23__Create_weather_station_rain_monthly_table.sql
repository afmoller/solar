CREATE SEQUENCE IF NOT EXISTS WEATHER_STATION_RAIN_MONTHLY_SEQ;

CREATE TABLE IF NOT EXISTS WEATHER_STATION_RAIN_MONTHLY (
    ID INTEGER PRIMARY KEY NOT NULL DEFAULT nextval('WEATHER_STATION_RAIN_MONTHLY_SEQ'),
    YEAR INTEGER,
    DATEUTC TIMESTAMPTZ NOT NULL,
    MONTHLYRAININ NUMERIC(6, 3) NOT NULL,
    YEARLYRAININ NUMERIC(6, 3) NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_YEAR_WEATHER_STATION_RAIN_MONTHLY ON WEATHER_STATION_RAIN_MONTHLY(YEAR);
CREATE INDEX IF NOT EXISTS IDX_DATEUTC_WEATHER_STATION_RAIN_MONTHLY ON WEATHER_STATION_RAIN_MONTHLY(DATEUTC);