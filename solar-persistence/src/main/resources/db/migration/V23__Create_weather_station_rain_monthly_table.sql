CREATE SEQUENCE IF NOT EXISTS WEATHER_STATION_RAIN_MONTHLY_SEQ;

CREATE TABLE WEATHER_STATION_RAIN_MONTHLY (
    ID_PK INTEGER PRIMARY KEY NOT NULL DEFAULT nextval('WEATHER_STATION_RAIN_MONTHLY_SEQ'),
    DATEUTC TIMESTAMPTZ NOT NULL,
    MONTHLYRAININ NUMERIC(6, 3) NOT NULL,
    YEARLYRAININ NUMERIC(6, 3) NOT NULL
);

CREATE INDEX IDX_DATEUTC_WEATHER_STATION_RAIN_MONTHLY ON WEATHER_STATION_RAIN_MONTHLY(DATEUTC);