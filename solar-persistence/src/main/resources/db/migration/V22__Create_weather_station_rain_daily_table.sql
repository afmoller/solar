CREATE SEQUENCE IF NOT EXISTS WEATHER_STATION_RAIN_DAILY_SEQ;

CREATE TABLE WEATHER_STATION_RAIN_DAILY (
    ID_PK INTEGER PRIMARY KEY NOT NULL DEFAULT nextval('WEATHER_STATION_RAIN_DAILY_SEQ'),
    DATEUTC TIMESTAMPTZ NOT NULL,
    DAILYRAININ NUMERIC(6, 3) NOT NULL,
    MONTHLYRAININ NUMERIC(6, 3) NOT NULL,
    YEARLYRAININ NUMERIC(6, 3) NOT NULL
);

CREATE INDEX IDX_DATEUTC_WEATHER_STATION_RAIN_DAILY ON WEATHER_STATION_RAIN_DAILY(DATEUTC);