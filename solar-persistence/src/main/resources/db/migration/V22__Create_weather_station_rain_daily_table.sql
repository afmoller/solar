CREATE SEQUENCE IF NOT EXISTS WEATHER_STATION_RAIN_DAILY_SEQ;

CREATE TABLE IF NOT EXISTS WEATHER_STATION_RAIN_DAILY (
    ID INTEGER PRIMARY KEY NOT NULL DEFAULT nextval('WEATHER_STATION_RAIN_DAILY_SEQ'),
    YEAR INTEGER,
    MONTH INTEGER,
    DATEUTC TIMESTAMPTZ NOT NULL,
    DAILYRAININ NUMERIC(6, 3) NOT NULL,
    MONTHLYRAININ NUMERIC(6, 3) NOT NULL,
    YEARLYRAININ NUMERIC(6, 3) NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_YEAR_WEATHER_STATION_RAIN_DAILY ON WEATHER_STATION_RAIN_DAILY(YEAR);
CREATE INDEX IF NOT EXISTS IDX_MONTH_WEATHER_STATION_RAIN_DAILY ON WEATHER_STATION_RAIN_DAILY(MONTH);
CREATE INDEX IF NOT EXISTS IDX_DATEUTC_WEATHER_STATION_RAIN_DAILY ON WEATHER_STATION_RAIN_DAILY(DATEUTC);